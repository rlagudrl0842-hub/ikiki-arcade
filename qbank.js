// 연령 모드 → 문제 묶음 (난이도 사다리: 한 단계 아래 문제도 일부 섞어 너무 어렵지만은 않게)
// 반환 형식은 기존 BELL과 같음: [문제, 정답, 오답...] + cat(분야)
export function bankFor(mode6) {
  const pick = (k) => (QBANK[k] || []).map(([cat, ...q]) => Object.assign(q, { cat }));
  switch (mode6) {
    case 'baby': case 'kid': return pick('kid');
    case 'elem': return pick('elem');
    case 'mid': return [...pick('mid'), ...pick('elem').filter((_, i) => i % 3 === 0)];
    case 'high': return [...pick('high'), ...pick('mid').filter((_, i) => i % 2 === 0)];
    case 'adult': return [...pick('adult'), ...pick('high')];
    default: return pick('elem');
  }
}
